const verificationForm = document.getElementById(
    "verificationForm"
);

const loginPage = document.getElementById("loginPage");
const resultPage = document.getElementById("resultPage");

const certificateInput = document.getElementById(
    "certificateId"
);

const errorMessage = document.getElementById(
    "errorMessage"
);

verificationForm.addEventListener("submit", function(event) {

    event.preventDefault();

    const enteredId = certificateInput.value
        .trim()
        .toUpperCase();

    const certificate = records[enteredId];

    // If certificate ID does not exist
    if (!certificate) {

        errorMessage.textContent =
            "Certificate ID not found. Please check and try again.";

        errorMessage.style.display = "block";

        return;
    }

    // Hide error message
    errorMessage.style.display = "none";

    // Show student details
    document.getElementById("studentName").textContent =
        certificate.name;

    document.getElementById("displayCertificateId").textContent =
        enteredId;

    document.getElementById("teamName").textContent =
        certificate.team;

    document.getElementById("statementId").textContent =
        certificate.statement;

    document.getElementById("statementName").textContent =
        certificate.statementName;


    // Show all 6 team members
    const teamMembers = document.getElementById(
        "teamMembers"
    );

    teamMembers.innerHTML = "";

    certificate.members.forEach(function(member, index) {

        const memberRow = document.createElement("div");

        memberRow.className = "member";

        memberRow.innerHTML = `
            <span class="member-number">
                ${index + 1}
            </span>

            <span>${member}</span>
        `;

        teamMembers.appendChild(memberRow);

    });


    // Move from login page to result page
    loginPage.classList.add("hidden");

    resultPage.classList.remove("hidden");

});


// Back button
document.getElementById("backButton").addEventListener(
    "click",
    function() {

        resultPage.classList.add("hidden");

        loginPage.classList.remove("hidden");

        certificateInput.value = "";

        certificateInput.focus();

    }
);